// The OpenAPIs of a service project — so the import does not start in «Downloads».
//
// A project keeps the APIs it wraps next to its helper (`04-helper/src/main/resources/
// openApi-crm.v2.json`, as the OpenApiGenerator reads them); the `OpenApi.yml` under
// `03-api` / `03-worker` is generated — the documentation of the project itself.
import { isSkippedDir } from '../domainScan';
import { handleFor } from '../projects';
import { ownFolders } from '../projectImport';
import type { Model } from '../types';

export interface ProjectOpenApi {
  /** relative to the project: `04-helper/src/main/resources/openApi-crm.v2.json` */
  path: string;
  name: string;
  /** generated by the project (its own API documentation) — not one it wraps */
  generated: boolean;
  file: FileSystemFileHandle;
}

const OPENAPI_FILE = /openapi.*\.(json|ya?ml)$/i;

/** Is the file the project's own, generated documentation (`03-api/OpenApi.yml`)? */
export const isGeneratedOpenApi = (path: string): boolean => /(^|\/)OpenApi\.(ya?ml|json)$/.test(path) && !/(^|\/)openApi-/.test(path);

/** The order: the wrapped APIs first (`openApi-…`), by path; the generated ones last. */
export function sortOpenApis<T extends { path: string; generated: boolean }>(files: T[]): T[] {
  return [...files].sort((a, b) => Number(a.generated) - Number(b.generated) || a.path.localeCompare(b.path));
}

async function collect(dir: FileSystemDirectoryHandle, prefix: string, out: ProjectOpenApi[], depth: number): Promise<void> {
  if (depth > 8) return;
  for await (const [name, handle] of dir.entries()) {
    const path = prefix ? `${prefix}/${name}` : name;
    if (handle.kind === 'directory') {
      if (!isSkippedDir(name)) await collect(handle as FileSystemDirectoryHandle, path, out, depth + 1);
    } else if (OPENAPI_FILE.test(name)) {
      out.push({ path, name, generated: isGeneratedOpenApi(path), file: handle as FileSystemFileHandle });
    }
  }
}

/**
 * The remembered project folder of the collection (Admin → Katalog → Projekt-Ordner, the
 * same rule as the Abgleich) and the OpenAPIs in it. `null`: no folder remembered or no access.
 */
export async function projectOpenApis(model: Model | null, project: string): Promise<{ folder: string; dir: FileSystemDirectoryHandle; files: ProjectOpenApi[] } | null> {
  for (const p of ownFolders(model, project)) {
    const dir = await handleFor(p).catch(() => null);
    if (!dir) continue;
    const files: ProjectOpenApi[] = [];
    await collect(dir, '', files, 0);
    return { folder: p.name, dir, files: sortOpenApis(files) };
  }
  return null;
}
